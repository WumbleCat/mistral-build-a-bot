/** Sticky header bar shared by every screen. `children` sit on the right. */
export function TopBar({
  onLogoClick,
  progress,
  children,
}: {
  onLogoClick?: () => void;
  /** 0..1 — drawn as a thin flame line along the bottom edge. */
  progress?: number;
  children?: ReactNode;
}) {
  return (
    <header className="sticky top-0 z-40 border-b border-line-soft/80 bg-canvas/85 backdrop-blur-lg">
      <div className="mx-auto flex h-16 w-full max-w-6xl items-center gap-4 px-4 sm:px-6">
        <Logo onClick={onLogoClick} />
        <div className="ml-auto flex min-w-0 items-center gap-2">{children}</div>
      </div>
      {progress !== undefined && (
        <div className="absolute inset-x-0 -bottom-px h-0.5 bg-transparent" aria-hidden>
          <div className="h-full bg-flame-500 transition-[width] duration-500" style={{ width: `${Math.round(progress * 100)}%` }} />
        </div>
      )}
    </header>
  );
}

export function Spinner({ label, className = '' }: { label?: string; className?: string }) {
  return (
    <span className={`inline-flex items-center gap-2.5 text-sm text-muted ${className}`}>
      <span className="size-4 animate-spin rounded-full border-2 border-line border-t-flame-400" aria-hidden />
      {label && <span>{label}</span>}
    </span>
  );
}

/** Centred modal card on a dimmed backdrop. Clicking the backdrop closes it. */
export function Modal({
  label,
  wide,
  onClose,
  children,
}: {
  label: string;
  wide?: boolean;
  onClose: () => void;
  children: ReactNode;
}) {
  return (
    <div
      className="fixed inset-0 z-[80] grid place-items-center bg-scrim/40 p-4 backdrop-blur-sm sm:p-6"
      role="dialog"
      aria-modal="true"
      aria-label={label}
      onClick={onClose}
    >
      <div
        className={`card stage-enter flex max-h-[90vh] w-full flex-col gap-4 overflow-y-auto p-5 sm:p-6 ${wide ? 'max-w-4xl' : 'max-w-2xl'}`}
        onClick={(e) => e.stopPropagation()}
      >
        {children}
      </div>
    </div>
  );
}

export function IllustrativeBadge({ children }: { children: ReactNode }) {
  return (
    <span className="pointer-events-none absolute top-5 right-5 rounded-full border border-line bg-surface/90 px-2.5 py-1 text-[10px] font-semibold tracking-[0.12em] text-muted uppercase backdrop-blur">
      {children}
    </span>
  );
}
