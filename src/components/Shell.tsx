import type { ReactNode } from 'react';
import { ScanSearch } from 'lucide-react';

/** Brand mark: the flame tile plus the two-tone wordmark. */
export function Logo({ onClick }: { onClick?: () => void }) {
  const Tag = onClick ? 'button' : 'div';
  return (
    <Tag {...(onClick ? { type: 'button' as const, onClick } : {})} className="group flex items-center gap-2.5 rounded-xl text-left">
      <span className="relative grid size-9 place-items-center rounded-xl bg-flame-500 text-on-accent shadow-lg shadow-flame-600/25">
        <ScanSearch className="size-5" strokeWidth={2.5} />
      </span>
      <span className="text-[15px] font-bold tracking-tight text-strong">
        Build<span className="text-flame-400">From</span>Vision
      </span>
    </Tag>
  );
}

