import { Link, NavLink, Outlet, useLocation } from 'react-router-dom'
import { LayoutGrid, LogOut, ScanSearch, Sparkles } from 'lucide-react'
import { useAuth } from '../context/AuthContext'
import DemoBanner from './DemoBanner'

function Logo() {
  return (
    <Link to="/" className="group flex items-center gap-2.5">
      <span className="relative grid size-9 place-items-center rounded-xl bg-flame-500 text-on-accent shadow-lg shadow-flame-600/25">
        <ScanSearch className="size-5" strokeWidth={2.5} />
      </span>
      <span className="text-[15px] font-bold tracking-tight">
        Build<span className="text-flame-400">From</span>Vision
      </span>
    </Link>
  )
}

const navLink = ({ isActive }) =>
  [
    'flex items-center gap-2 rounded-lg px-3 py-2 text-sm font-medium transition',
    isActive ? 'bg-line-soft text-strong' : 'text-muted hover:bg-sunken hover:text-strong',
  ].join(' ')

export default function Layout() {
  const { user, isAnonymous, signOut, configured } = useAuth()
  const { pathname } = useLocation()

  return (
    <div className="flex min-h-dvh flex-col">
      <header className="sticky top-0 z-40 border-b border-line-soft/80 bg-canvas/85 backdrop-blur-lg">
        <div className="mx-auto flex h-16 w-full max-w-6xl items-center gap-4 px-4 sm:px-6">
          <Logo />

          <nav className="ml-auto flex items-center gap-1">
            {user && (
              <NavLink to="/builds" className={navLink}>
                <LayoutGrid className="size-4" />
                <span className="hidden sm:inline">My builds</span>
              </NavLink>
            )}
            {pathname !== '/' && (
              <NavLink to="/" className={navLink} end>
                <Sparkles className="size-4" />
                <span className="hidden sm:inline">New build</span>
              </NavLink>
            )}

            {user ? (
              <div className="ml-2 flex items-center gap-2 border-l border-line-soft pl-3">
                <span className="hidden max-w-[16ch] truncate text-xs text-muted sm:block">
                  {isAnonymous ? 'Guest session' : user.email}
                </span>
                <button
                  type="button"
                  onClick={signOut}
                  title="Sign out"
                  className="rounded-lg p-2 text-muted transition hover:bg-sunken hover:text-strong"
                >
                  <LogOut className="size-4" />
                </button>
              </div>
            ) : (
              configured && (
                <Link to="/signin" className="btn-ghost ml-2 px-3 py-2">
                  Sign in
                </Link>
              )
            )}
          </nav>
        </div>
      </header>

      <DemoBanner />

      <main className="mx-auto w-full max-w-6xl flex-1 px-4 py-8 sm:px-6 sm:py-12">
        <Outlet />
      </main>

      <footer className="border-t border-line-soft/80 py-6">
        <div className="mx-auto flex w-full max-w-6xl flex-wrap items-center justify-between gap-3 px-4 text-xs text-muted sm:px-6">
          <p>Vision, bill of materials and build steps generated by Mistral. Verify parts before ordering.</p>
          <p className="font-mono">React · Supabase · Mistral</p>
        </div>
      </footer>
    </div>
  )
}
